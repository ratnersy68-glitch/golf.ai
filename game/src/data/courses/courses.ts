import type { Atmosphere, CourseData, HoleSummary } from '../types';

/**
 * Real-course metadata. Hole pars and yardages are championship-tee figures from public scorecards
 * (rounded). `layoutId` marks holes that have been recreated in miniature so far.
 */

type Row = [par: number, yards: number, name?: string];
const holes = (rows: Row[], built: Record<number, string> = {}): HoleSummary[] =>
  rows.map(([par, yards, name], i) => ({ number: i + 1, par, yards, name, layoutId: built[i + 1] }));

